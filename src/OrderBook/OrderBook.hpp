#pragma once

#include <cstddef>
#include <cstdint>
#include <optional>
#include <span>
#include <vector>

// Prices are integer ticks (e.g. price * 100 for cents) so comparisons are exact
// and cheap; convert at the edge of the system, never inside the book.
using OrderId  = std::uint64_t;
using Price    = std::int64_t;
using Quantity = std::uint32_t;

enum class Side : std::uint8_t { Buy = 0, Sell };

enum class OrderType : std::uint8_t { Limit = 0, Market };

// Market orders never rest, so they are always treated as IOC (or FOK if asked).
enum class TimeInForce : std::uint8_t { GoodTillCancel = 0, ImmediateOrCancel, FillOrKill };

enum class OrderStatus : std::uint8_t
{
    New,             // rested without trading
    PartiallyFilled, // traded, remainder rested
    Filled,          // fully traded
    Cancelled,       // remainder dropped (IOC/market leftover, FOK kill)
    Rejected         // invalid input or order pool exhausted
};

// Single-threaded price-time priority matching engine. Feed it from one thread
// (e.g. the consumer side of an SPSCQueue); it is not internally synchronized.
//
// Hot-path properties:
//  - orders live in a fixed pool allocated up front; no allocation per order
//  - OrderId encodes the pool slot, so cancel/lookup is O(1) without hashing
//  - each side is a contiguous sorted array of levels with the best at the back,
//    so touching the top of book never shifts more than a few elements
class OrderBook final
{
public:
    struct Trade
    {
        OrderId maker;
        OrderId taker;
        Price price;
        Quantity qty;
        Side takerSide;
    };

    struct ExecReport
    {
        OrderId id;
        OrderStatus status;
        Quantity filled;
        Quantity remaining;
    };

    struct DepthLevel
    {
        Price price;
        std::uint64_t qty;
    };

    struct OrderInfo
    {
        OrderId id;
        Side side;
        Price price;
        Quantity qty;
    };

    explicit OrderBook(std::uint32_t maxOrders, std::size_t expectedLevels = 4096);

    OrderBook(const OrderBook&) = delete;
    OrderBook& operator=(const OrderBook&) = delete;

    ExecReport submit(Side side, OrderType type, TimeInForce tif, Price price, Quantity qty);

    bool cancel(OrderId id) noexcept;

    // Lowers the quantity in place, keeping time priority. newQty == 0 cancels.
    bool reduce(OrderId id, Quantity newQty) noexcept;

    // Cancel/replace: loses time priority and returns a new id.
    ExecReport replace(OrderId id, Price price, Quantity qty);

    // Trades generated by the most recent submit()/replace(). The view is
    // invalidated by the next call to either.
    std::span<const Trade> trades() const noexcept { return tradeBuf; }

    std::optional<Price> bestBid() const noexcept;
    std::optional<Price> bestAsk() const noexcept;
    std::uint64_t volumeAt(Side side, Price price) const noexcept;
    std::vector<DepthLevel> depth(Side side, std::size_t levels) const;
    std::optional<OrderInfo> find(OrderId id) const noexcept;

    std::size_t orderCount() const noexcept { return liveOrders; }
    std::size_t levelCount(Side side) const noexcept
    {
        return side == Side::Buy ? bids.size() : asks.size();
    }

private:
    static constexpr std::uint32_t npos = UINT32_MAX;

    // 32 bytes: two orders per cache line.
    struct Node
    {
        OrderId id; // 0 when the slot is free
        Price price;
        Quantity qty;
        std::uint32_t prev;
        std::uint32_t next; // doubles as the free-list link
        Side side;
    };

    struct PriceLevel
    {
        Price price;
        std::uint64_t qty;
        std::uint32_t head;
        std::uint32_t tail;
    };

    // bids ascending, asks descending: best price is always at back().
    using Levels = std::vector<PriceLevel>;

    template <Side S> Levels& levels() noexcept { return S == Side::Buy ? bids : asks; }
    template <Side S> const Levels& levels() const noexcept { return S == Side::Buy ? bids : asks; }

    template <Side S> ExecReport submitImpl(OrderType type, TimeInForce tif, Price price, Quantity qty);
    template <Side S> Quantity match(OrderId takerId, Price limit, Quantity qty);
    template <Side S> bool canFill(Price limit, Quantity qty) const noexcept;
    template <Side S> void rest(std::uint32_t idx);
    template <Side S> void unlink(std::uint32_t idx) noexcept;
    template <Side S> Levels::const_iterator findLevel(Price price) const noexcept;

    std::uint32_t allocNode() noexcept;
    void freeNode(std::uint32_t idx) noexcept;
    const Node* lookup(OrderId id) const noexcept;

    std::vector<Node> nodes;
    std::uint32_t freeHead{npos};
    std::uint64_t nextSeq{1};
    std::size_t liveOrders{0};

    Levels bids;
    Levels asks;
    std::vector<Trade> tradeBuf;
};
